describe('edges', () => {
  it('goes through the barrel to the declaring file, per symbol, with type-only weight', () => {
    expect(edge('src/services/album.service.ts', 'src/dtos/album.dto.ts')).toEqual({
      from: 'src/services/album.service.ts', to: 'src/dtos/album.dto.ts', weight: 1, typeOnly: false, kinds: ['import', 'reexport'], symbols: ['AlbumDto', 'AlbumQuery'],
    });
    expect(edge('src/services/album.service.ts', 'src/dtos/user.dto.ts')).toEqual({
      from: 'src/services/album.service.ts', to: 'src/dtos/user.dto.ts', weight: 0.5, typeOnly: true, kinds: ['import'], symbols: ['UserDto'],
    });
    expect(facts.edges.some((candidate) => candidate.to === 'src/dtos/index.ts')).toBe(false);
  });

  it('adds member edges for this.x typed as a class from another file, through an inherited parameter property', () => {
    expect(edge('src/services/album.service.ts', 'src/repositories/album.repository.ts')).toMatchObject({ kinds: ['member'], symbols: ['AlbumRepository'], weight: 1 });
    expect(edge('src/services/album.service.ts', 'src/repositories/user.repository.ts')).toMatchObject({ kinds: ['member', 'typeof-import'], symbols: ['UserRepository'], weight: 1 });
    expect(edge('src/controllers/album.controller.ts', 'src/services/album.service.ts')?.kinds).toEqual(['import', 'member']);
  });

  it('keeps namespace, side-effect and dynamic-import kinds, and only edges between movable files', () => {
    expect(edge('src/services/album.service.ts', 'src/utils/strings.ts')).toMatchObject({ kinds: ['namespace-import'], symbols: ['*'] });
    expect(edge('src/app.module.ts', 'src/setup.ts')?.kinds).toEqual(['side-effect']);
    expect(edge('src/services/album.service.ts', 'src/utils/lazy.ts')?.kinds).toEqual(['dynamic-import']);
    const movable = new Set(facts.files.map((file) => file.path));
    expect(facts.edges.every((candidate) => movable.has(candidate.from) && movable.has(candidate.to) && candidate.from !== candidate.to)).toBe(true);
    const keys = facts.edges.map((candidate) => `${candidate.from}\0${candidate.to}`);
    expect(keys).toEqual([...keys].sort());
  });
});

