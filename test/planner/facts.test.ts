function gitRepo(tree: Record<string, string>): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ac-facts-'));
  for (const [file, text] of Object.entries(tree)) {
    fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
    fs.writeFileSync(path.join(root, file), text);
  }
  const git = (...args: string[]) => execFileSync('git', ['-C', root, ...args], { stdio: ['ignore', 'pipe', 'pipe'] });
  git('init', '-q');
  git('config', 'user.email', 'fixtures@ac.invalid');
  git('config', 'user.name', 'fixtures');
  git('add', '-A');
  git('commit', '-q', '-m', 'fixture');
  return root;
}

/** The same tree without git or a disk: proves facts only read through the RepoFs. */
function memoryRepoFs(root: string, tree: Record<string, string>): RepoFs {
  const tracked = Object.keys(tree).sort();
  const relative = (absolutePath: string) => path.relative(root, absolutePath).split(path.sep).join('/');
  const entries = (absolutePath: string) => {
    const prefix = relative(absolutePath) ? `${relative(absolutePath)}/` : '';
    const files = new Set<string>();
    const directories = new Set<string>();
    for (const file of tracked.filter((candidate) => candidate.startsWith(prefix))) {
      const rest = file.slice(prefix.length);
      if (rest.includes('/')) directories.add(rest.slice(0, rest.indexOf('/')));
      else files.add(rest);
    }
    return { files: [...files], directories: [...directories] };
  };
  return {
    root,
    tracked: () => tracked,
    read: (file) => tree[file],
    fileExists: (absolutePath) => relative(absolutePath) in tree,
    directoryExists: (absolutePath) => !relative(absolutePath).startsWith('..') && (relative(absolutePath) === '' || tracked.some((file) => file.startsWith(`${relative(absolutePath)}/`))),
    entries,
    realpath: (absolutePath) => absolutePath,
  };
}

